-- Año Escolar: Motor central del sistema
CREATE TABLE IF NOT EXISTS public.school_years (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              text NOT NULL,               -- '2026-2027'
  start_date        date NOT NULL,
  end_date          date NOT NULL,
  enrollment_start  date,                        -- Ventana de inscripciones
  enrollment_end    date,
  reenrollment_start date,                       -- Ventana de reinscripciones
  reenrollment_end  date,
  status            text DEFAULT 'draft'
                    CHECK (status IN (
                      'draft','enrollment','reenrollment',
                      'active','closed','archived'
                    )),
  created_by        uuid REFERENCES public.profiles(id),
  created_at        timestamp with time zone DEFAULT now() NOT NULL,
  updated_at        timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT valid_dates CHECK (end_date > start_date),
  CONSTRAINT valid_enrollment CHECK (
    enrollment_start IS NULL OR enrollment_end IS NULL
    OR enrollment_end >= enrollment_start
  ),
  CONSTRAINT valid_reenrollment CHECK (
    reenrollment_start IS NULL OR reenrollment_end IS NULL
    OR reenrollment_end >= reenrollment_start
  )
);

-- Solo un año puede estar activo/inscripción/reinscripción a la vez
CREATE UNIQUE INDEX IF NOT EXISTS idx_school_years_one_active
  ON public.school_years (status)
  WHERE status IN ('active', 'enrollment', 'reenrollment');

-- Períodos académicos: ahora con school_year_id
CREATE TABLE IF NOT EXISTS public.academic_periods (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_year_id    bigint NOT NULL REFERENCES public.school_years(id) ON DELETE CASCADE,
  name              text NOT NULL,               -- 'Periodo 1', 'Periodo 2', 'Periodo 3'
  start_date        date NOT NULL,
  end_date          date NOT NULL,
  order_index       integer NOT NULL DEFAULT 1,  -- Para ordenar: 1, 2, 3...
  status            text DEFAULT 'pending'
                    CHECK (status IN ('pending','open','closed')),
  is_active         boolean DEFAULT false,
  created_at        timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT valid_period_dates CHECK (end_date > start_date),
  CONSTRAINT unique_period_order UNIQUE (school_year_id, order_index)
);

-- Migrar datos de periods existentes a academic_periods si hay datos
-- (Ejecutar solo si ya tienes periods con datos)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='public' AND table_name='periods') THEN
    IF EXISTS (SELECT 1 FROM public.periods WHERE start_date IS NOT NULL LIMIT 1) THEN
      -- Crear un año escolar de respaldo si no existe
      IF NOT EXISTS (SELECT 1 FROM public.school_years LIMIT 1) THEN
        BEGIN
          INSERT INTO public.school_years (name, start_date, end_date, status, created_at)
          SELECT
            EXTRACT(YEAR FROM min(start_date))::text || '-' || (EXTRACT(YEAR FROM max(start_date))::int + 1)::text,
            min(start_date)::date,
            COALESCE(max(end_date), (max(start_date) + interval '1 year'))::date,
            'archived',
            now()
          FROM public.periods
          WHERE start_date IS NOT NULL
          GROUP BY EXTRACT(YEAR FROM min(start_date));
        EXCEPTION WHEN OTHERS THEN
          RAISE NOTICE 'Skip school_years migration: %', SQLERRM;
        END;
      END IF;

      -- Migrar períodos existentes al primer año escolar creado
      IF EXISTS (SELECT 1 FROM public.school_years LIMIT 1) THEN
        BEGIN
          INSERT INTO public.academic_periods (school_year_id, name, start_date, end_date, order_index, status, is_active, created_at)
          SELECT
            (SELECT id FROM public.school_years ORDER BY created_at DESC LIMIT 1),
            p.name,
            p.start_date,
            p.end_date,
            ROW_NUMBER() OVER (ORDER BY p.start_date)::int,
            CASE WHEN p.status = 'open' THEN 'open' ELSE 'closed' END,
            COALESCE(p.is_active, false),
            COALESCE(p.created_at, now())
          FROM public.periods p
          WHERE p.start_date IS NOT NULL
          ON CONFLICT DO NOTHING;
        EXCEPTION WHEN OTHERS THEN
          RAISE NOTICE 'Skip academic_periods migration: %', SQLERRM;
        END;
      END IF;
    END IF;
  END IF;
END $$;

