-- Datos del año escolar para el padre
CREATE OR REPLACE FUNCTION public.get_parent_year_data(p_parent_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER STABLE SET search_path = public AS $$
DECLARE
  v_year jsonb;
  v_periods jsonb;
  v_students jsonb;
  v_history jsonb;
BEGIN
  v_year := public.get_active_school_year();

  IF (v_year->>'id') IS NOT NULL THEN
    v_periods := public.get_periods_for_year((v_year->>'id')::bigint);
  ELSE
    v_periods := '[]'::jsonb;
  END IF;

  -- Estudiantes del padre en el año activo
  SELECT jsonb_agg(jsonb_build_object(
    'id', s.id,
    'name', s.name,
    'classroom_id', s.classroom_id,
    'classroom_name', c.name,
    'grade_level', c.level,
    'enrollment_type', s.enrollment_type
  )) INTO v_students
  FROM public.students s
  LEFT JOIN public.classrooms c ON c.id = s.classroom_id
  WHERE s.parent_id = p_parent_id AND s.deleted_at IS NULL;

  -- Historial del padre (todos los años)
  SELECT jsonb_agg(
    jsonb_build_object(
      'school_year_name', sy.name,
      'grade_level', sh.grade_level,
      'classroom_name', sh.classroom_name,
      'teacher_name', sh.teacher_name,
      'average_score', sh.average_score,
      'attendance_pct', sh.attendance_pct,
      'status', sh.status
    ) ORDER BY sy.start_date DESC
  ) INTO v_history
  FROM public.student_history sh
  JOIN public.school_years sy ON sy.id = sh.school_year_id
  WHERE sh.student_id IN (
    SELECT id FROM public.students WHERE parent_id = p_parent_id
  );

  RETURN jsonb_build_object(
    'school_year', v_year,
    'periods', COALESCE(v_periods, '[]'::jsonb),
    'students', COALESCE(v_students, '[]'::jsonb),
    'history', COALESCE(v_history, '[]'::jsonb)
  );
END;
$$;
