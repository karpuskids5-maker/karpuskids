-- ---- supervision_sessions ------------------------------------------------
CREATE TABLE IF NOT EXISTS public.supervision_sessions (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classroom_id    bigint REFERENCES public.classrooms(id) ON DELETE CASCADE,
  supervisor_id   uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  supervisor_role text CHECK (supervisor_role IN ('directora','asistente','admin')),
  notes           text,
  status          text DEFAULT 'active' CHECK (status IN ('active','closed')),
  started_at      timestamp with time zone DEFAULT now() NOT NULL,
  ended_at        timestamp with time zone,
  created_at      timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_supervision_sessions_active
  ON public.supervision_sessions (supervisor_id, status);

CREATE INDEX IF NOT EXISTS idx_supervision_sessions_classroom
  ON public.supervision_sessions (classroom_id, started_at DESC);


-- ---- supervision_audits (intervenciones) ---------------------------------
CREATE TABLE IF NOT EXISTS public.supervision_audits (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            text UNIQUE,
  session_id      bigint REFERENCES public.supervision_sessions(id) ON DELETE SET NULL,
  classroom_id    bigint REFERENCES public.classrooms(id) ON DELETE CASCADE,
  teacher_id      uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  supervisor_id   uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  supervisor_role text CHECK (supervisor_role IN ('directora','asistente','admin')),
  priority        text DEFAULT 'media'  CHECK (priority IN ('alta','media','baja')),
  status          text DEFAULT 'abierta' CHECK (status IN ('abierta','en_proceso','resuelta')),
  category        text DEFAULT 'pedagogica',
  reason          text NOT NULL,
  action_taken    text,
  notes           text,
  created_at      timestamp with time zone DEFAULT now() NOT NULL,
  resolved_at     timestamp with time zone
);

CREATE INDEX IF NOT EXISTS idx_supervision_audits_classroom
  ON public.supervision_audits (classroom_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_supervision_audits_status
  ON public.supervision_audits (status, priority);


-- ---- Generador de codigo unico de intervencion (INT-YYYY-XXXX) -----------
CREATE OR REPLACE FUNCTION public.generate_intervention_code()
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
declare
  v_year text := to_char(now(), 'YYYY');
  v_seq  int;
  v_code text;
begin
  select count(*)::int + 1 into v_seq
  from public.supervision_audits
  where code like 'INT-' || v_year || '-%';

  loop
    v_code := 'INT-' || v_year || '-' || lpad(v_seq::text, 4, '0');
    exit when not exists (select 1 from public.supervision_audits where code = v_code);
    v_seq := v_seq + 1;
  end loop;

  return v_code;
end;
$$;

-- Rellena el codigo automaticamente si el cliente no lo envia.
CREATE OR REPLACE FUNCTION public.tg_supervision_audit_code()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
begin
  if new.code is null or new.code = '' then
    new.code := public.generate_intervention_code();
  end if;
  return new;
end;
$$;

DROP TRIGGER IF EXISTS trg_supervision_audit_code ON public.supervision_audits;
CREATE TRIGGER trg_supervision_audit_code
  BEFORE INSERT ON public.supervision_audits
  FOR EACH ROW EXECUTE FUNCTION public.tg_supervision_audit_code();

-- Marca la fecha de resolucion cuando el estado pasa a 'resuelta'.
CREATE OR REPLACE FUNCTION public.tg_supervision_audit_resolve()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
begin
  if new.status = 'resuelta' and (old.status is distinct from 'resuelta') then
    new.resolved_at := now();
  end if;
  return new;
end;
$$;

DROP TRIGGER IF EXISTS trg_supervision_audit_resolve ON public.supervision_audits;
CREATE TRIGGER trg_supervision_audit_resolve
  BEFORE UPDATE ON public.supervision_audits
  FOR EACH ROW EXECUTE FUNCTION public.tg_supervision_audit_resolve();


-- ---- Row Level Security --------------------------------------------------
ALTER TABLE public.supervision_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.supervision_audits   ENABLE ROW LEVEL SECURITY;

-- supervision_sessions: solo staff directivo gestiona sus propias sesiones.
DROP POLICY IF EXISTS supervision_sessions_staff ON public.supervision_sessions;
CREATE POLICY supervision_sessions_staff ON public.supervision_sessions FOR ALL
  USING (get_my_role() IN ('directora','asistente','admin'))
  WITH CHECK (get_my_role() IN ('directora','asistente','admin'));

-- supervision_audits: staff directivo lectura/escritura total.
DROP POLICY IF EXISTS supervision_audits_staff ON public.supervision_audits;
CREATE POLICY supervision_audits_staff ON public.supervision_audits FOR ALL
  USING (get_my_role() IN ('directora','asistente','admin'))
  WITH CHECK (get_my_role() IN ('directora','asistente','admin'));

-- supervision_audits: la maestra puede leer las intervenciones que la afectan.
DROP POLICY IF EXISTS supervision_audits_teacher_read ON public.supervision_audits;
CREATE POLICY supervision_audits_teacher_read ON public.supervision_audits FOR SELECT
  USING (get_my_role() = 'maestra' AND teacher_id = auth.uid());


