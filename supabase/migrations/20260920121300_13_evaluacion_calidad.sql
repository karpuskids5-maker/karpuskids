-- Abre el periodo del mes anterior. Idempotente: si ya existe, no hace nada.
-- El dia 1 de octubre se crea el periodo de septiembre.
CREATE OR REPLACE FUNCTION public.quality_activate_previous_month()
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_month  date;
  v_id     bigint;
BEGIN
  -- Primer dia del mes anterior. El 1 de octubre se evalua septiembre.
  v_month := date_trunc('month', now() - interval '1 month')::date;

  INSERT INTO public.quality_periods (period_month, opens_at, closes_at, status)
  VALUES (
    v_month,
    date_trunc('month', now()),
    date_trunc('month', now()) + interval '1 month',
    'open'
  )
  ON CONFLICT (period_month) DO NOTHING
  RETURNING id INTO v_id;

  -- Ya existía: devolvemos el id para que la llamada sea inocua.
  IF v_id IS NULL THEN
    SELECT id INTO v_id FROM public.quality_periods WHERE period_month = v_month;
  END IF;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION public.quality_activate_previous_month() IS
  'Crea y abre el periodo correspondiente al mes anterior. Idempotente. Se invoca el dia 1 (secciones 3 y 21).';


-- Cierra los periodos cuya fecha de cierre ya paso (seccion 3).
CREATE OR REPLACE FUNCTION public.quality_close_expired()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_n integer;
BEGIN
  UPDATE public.quality_periods
     SET status = 'closed'
   WHERE status = 'open'
     AND now() > closes_at;
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n;
END;
$$;

