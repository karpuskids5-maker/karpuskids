-- Alerta de descenso: dimension que cae >= 0.5 puntos frente al periodo
-- anterior, con al menos 3 respuestas para que la muestra signifique algo.
CREATE OR REPLACE FUNCTION public.quality_generate_alerts(p_period_id bigint)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_institutional integer := 0;
  v_teacher       integer := 0;
  v_min_answers CONSTANT integer := 3;
  v_drop       CONSTANT numeric := 0.5;
BEGIN
  -- Descenso institucional (Bloque B) e IGSM
  INSERT INTO public.quality_alerts (period_id, kind, scope, dimension_key, message)
  SELECT cur.period_id,
         'descenso',
         'institucion',
         cur.question_key,
         format(
           'La puntuación de "%s" disminuyó de %s a %s respecto al período anterior (%s respuestas). Se recomienda revisar los comentarios antes de tomar cualquier decisión.',
           cur.prompt, prev.avg_score, cur.avg_score, cur.answers
         )
    FROM public.v_quality_dimension_scores cur
    JOIN public.v_quality_dimension_scores prev
      ON prev.question_key = cur.question_key
     AND prev.period_month = (
           SELECT max(p2.period_month) FROM public.v_quality_dimension_scores p2
           WHERE p2.period_month < cur.period_month AND p2.question_key = cur.question_key
         )
   WHERE cur.period_id = p_period_id
     AND cur.block = 'institucion'
     AND cur.answers >= v_min_answers
     AND prev.avg_score IS NOT NULL
     AND (prev.avg_score - cur.avg_score) >= v_drop
  ON CONFLICT (period_id, kind, scope, dimension_key,
               (COALESCE(teacher_id, '00000000-0000-0000-0000-000000000000'::uuid)))
  DO NOTHING;

  GET DIAGNOSTICS v_institutional = ROW_COUNT;

  -- Descenso por docente (Bloque A), sobre la matriz de dimensiones
  INSERT INTO public.quality_alerts (period_id, kind, scope, teacher_id, dimension_key, message)
  SELECT cur.period_id,
         'descenso',
         'docente',
         cur.teacher_id,
         cur.question_key,
         format(
           'La puntuación de "%s" de %s disminuyó de %s a %s respecto al período anterior (%s respuestas). Se recomienda revisar los comentarios asociados.',
           cur.prompt, coalesce(cur.teacher_name, 'la docente'), prev.avg_score, cur.avg_score, cur.answers
         )
    FROM public.v_quality_teacher_dimensions cur
    JOIN public.v_quality_teacher_dimensions prev
      ON prev.teacher_id = cur.teacher_id
     AND prev.question_key = cur.question_key
     AND prev.period_month = (
           SELECT max(p2.period_month) FROM public.v_quality_teacher_dimensions p2
           WHERE p2.period_month < cur.period_month
             AND p2.teacher_id = cur.teacher_id
             AND p2.question_key = cur.question_key
         )
   WHERE cur.period_id = p_period_id
     AND cur.answers >= v_min_answers
     AND prev.avg_score IS NOT NULL
     AND (prev.avg_score - cur.avg_score) >= v_drop
  ON CONFLICT (period_id, kind, scope, dimension_key,
               (COALESCE(teacher_id, '00000000-0000-0000-0000-000000000000'::uuid)))
  DO NOTHING;

  GET DIAGNOSTICS v_teacher = ROW_COUNT;

  RETURN v_institutional + v_teacher;
END;
$$;

COMMENT ON FUNCTION public.quality_generate_alerts(bigint) IS
  'Genera alertas de descenso comparando el periodo contra el anterior. Exige 3+ respuestas por dimension para no alertar por ruido de muestra (seccion 12). Devuelve cuantas alertas NUEVAS creo; reejecutarla no duplica.';


-- Punto de entrada unico del cron. Corre a diario y decide que hacer.
CREATE OR REPLACE FUNCTION public.quality_daily()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_day        integer := EXTRACT(DAY FROM now())::integer;
  v_opened     bigint;
  v_last_closed bigint;
  v_alerts     integer := 0;
  v_reminder   integer := 0;
BEGIN
  -- 1) Cerrar lo vencido y, de paso, calcular sus alertas de descenso.
  --    OJO: un periodo siempre vence el dia 1, asi que este paso y el de apertura
  --    ocurren el mismo dia. Por eso NO se corta despues de abrir.
  FOR v_last_closed IN
    SELECT id FROM public.quality_periods
     WHERE status = 'open' AND now() > closes_at
  LOOP
    v_alerts := v_alerts + public.quality_generate_alerts(v_last_closed);
  END LOOP;

  PERFORM public.quality_close_expired();

  -- 2) Dia 1: abrir el periodo del mes anterior
  IF v_day = 1 THEN
    v_opened := public.quality_activate_previous_month();
    v_reminder := public.quality_register_reminders(1);
  END IF;

  -- 3) Dias 7 / 15 / 25: recordatorio a las familias pendientes
  IF v_day IN (7,15,25) THEN
    v_reminder := public.quality_register_reminders(v_day::smallint);
  END IF;

  RETURN jsonb_build_object(
    'day',       v_day,
    'opened',    v_opened,
    'closed',    v_last_closed,
    'reminders', v_reminder,
    'alerts',    v_alerts
  );
END;
$$;

COMMENT ON FUNCTION public.quality_daily() IS
  'Entrada unica del cron diario: abre periodos el dia 1, cierra vencidos, registra recordatorios 7/15/25 y calcula alertas al cerrar (seccion 21). Todo en SQL, sin pg_net.';


