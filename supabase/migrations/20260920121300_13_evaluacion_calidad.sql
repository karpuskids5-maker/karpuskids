-- ══════════════════════════════════════════════════════════════════════════════
-- Envio atomico de la encuesta
-- ══════════════════════════════════════════════════════════════════════════════
-- El cliente NO inserta respuesta y respuestas por separado: si el segundo
-- INSERT fallara (validacion, red) dejaria una respuesta sin respuestas, y el
-- UNIQUE (period_id, student_id) impediria al padre reintentar. Esta funcion lo
-- resuelve en una sola transaccion.
--
-- Es SECURITY DEFINER, asi que ignora las RLS de arriba: por eso vuelve a
-- validar TODAS las condiciones a mano. Es la unica puerta de escritura de
-- los padres y no acepta p_parent_id: la identidad sale de auth.uid().
CREATE OR REPLACE FUNCTION public.quality_submit_survey(
  p_period_id          bigint,
  p_student_id         bigint,
  p_overall_score      smallint,
  p_teacher_comment    text DEFAULT NULL,
  p_general_comment    text DEFAULT NULL,
  p_comment_anonymous  boolean DEFAULT false,
  p_answers            jsonb DEFAULT '[]'::jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid        uuid := auth.uid();
  v_teacher_id uuid;
  v_response_id bigint;
  v_item       jsonb;
  v_question_id bigint;
  v_score      smallint;
  v_matched    integer;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'No autenticado' USING ERRCODE = '42501';
  END IF;

  -- 1) El alumno debe ser hijo de quien responde y estar activo.
  SELECT s.classroom_id INTO v_teacher_id
    FROM public.students s
   WHERE s.id = p_student_id
     AND s.parent_id = v_uid
     AND COALESCE(s.is_active, true)
     AND s.deleted_at IS NULL;

  IF v_teacher_id IS NULL THEN
    RAISE EXCEPTION 'El alumno no corresponde a tu familia' USING ERRCODE = '42501';
  END IF;

  -- 2) El periodo debe estar abierto y dentro de su ventana.
  IF NOT EXISTS (
    SELECT 1 FROM public.quality_periods p
     WHERE p.id = p_period_id
       AND p.status = 'open'
       AND now() BETWEEN p.opens_at AND p.closes_at
  ) THEN
    RAISE EXCEPTION 'El periodo de evaluacion no esta abierto' USING ERRCODE = '22023';
  END IF;

  -- 3) El IGSM es obligatorio y va de 1 a 5.
  IF p_overall_score IS NULL OR p_overall_score NOT BETWEEN 1 AND 5 THEN
    RAISE EXCEPTION 'Debes calificar tu satisfaccion general' USING ERRCODE = '22023';
  END IF;

  -- 4) La docente evaluada se congela al momento del envio.
  SELECT c.teacher_id INTO v_teacher_id
    FROM public.students s
    LEFT JOIN public.classrooms c ON c.id = s.classroom_id
   WHERE s.id = p_student_id;

  INSERT INTO public.quality_responses (
    period_id, student_id, parent_id, teacher_id, overall_score,
    teacher_comment, general_comment, comment_anonymous
  )
  VALUES (
    p_period_id, p_student_id, v_uid, v_teacher_id, p_overall_score,
    nullif(btrim(coalesce(p_teacher_comment, '')), ''),
    nullif(btrim(coalesce(p_general_comment, '')), ''),
    coalesce(p_comment_anonymous, false)
  )
  RETURNING id INTO v_response_id;

  -- 5) Puntajes. question_key y no id: el cliente no depende del seed.
  FOR v_item IN SELECT * FROM jsonb_array_elements(coalesce(p_answers, '[]'::jsonb))
  LOOP
    v_score := (v_item ->> 'score')::smallint;
    IF v_score IS NULL OR v_score NOT BETWEEN 1 AND 5 THEN
      RAISE EXCEPTION 'Puntaje invalido en la encuesta' USING ERRCODE = '22023';
    END IF;

    SELECT q.id INTO v_question_id
      FROM public.quality_questions q
     WHERE q.question_key = (v_item ->> 'question_key')
       AND q.is_active;

    IF v_question_id IS NULL THEN
      RAISE EXCEPTION 'Pregunta no valida: %', (v_item ->> 'question_key')
        USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.quality_answers (response_id, question_id, score)
    VALUES (v_response_id, v_question_id, v_score);
  END LOOP;

  -- 6) Se exigio responder TODAS las preguntas activas del catalogo.
  SELECT count(*) INTO v_matched
    FROM public.quality_answers a
    JOIN public.quality_questions q ON q.id = a.question_id
   WHERE a.response_id = v_response_id
     AND q.is_active;

  IF v_matched < (SELECT count(*) FROM public.quality_questions WHERE is_active) THEN
    RAISE EXCEPTION 'Faltan preguntas por responder' USING ERRCODE = '22023';
  END IF;

  RETURN v_response_id;
END;
$$;

COMMENT ON FUNCTION public.quality_submit_survey(bigint, bigint, smallint, text, text, boolean, jsonb) IS
  'Envia la encuesta completa en una transaccion. Valida identidad, ventana del periodo, escala 1-5 y que esten todas las preguntas activas. Idempotente por el UNIQUE del periodo: reintentar da error de duplicado.';


