BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    RAISE NOTICE 'pg_cron no esta instalado: se omite la automatizacion. La evaluacion se abre a mano con SELECT public.quality_activate_previous_month().';
    RETURN;
  END IF;

  -- Un solo trabajo. quality_daily() ya es idempotente en todas sus ramas.
  IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'quality-daily') THEN
    PERFORM cron.unschedule('quality-daily');
  END IF;

  -- 07:10 hora local del servidor: corre cuando el panel no esta en uso pico,
  -- y suficientemente despues del cierre de periodo del dia 1.
  PERFORM cron.schedule('quality-daily', '10 7 * * *', 'SELECT public.quality_daily()');
EXCEPTION
  WHEN insufficient_privilege THEN
    RAISE NOTICE 'Sin permisos para agendar cron: se omite la automatizacion.';
  WHEN OTHERS THEN
    RAISE NOTICE 'No se pudo agendar el cron de evaluacion: %', SQLERRM;
END;
$$;

COMMIT;
