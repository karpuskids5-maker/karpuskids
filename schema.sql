DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    BEGIN PERFORM cron.unschedule('karpus-mark-overdue'); EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN PERFORM cron.unschedule('karpus-payment-reminders-daily'); EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN PERFORM cron.unschedule('karpus-payment-cycle'); EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN PERFORM cron.unschedule('annual-payment-generator'); EXCEPTION WHEN OTHERS THEN NULL; END;

    PERFORM cron.schedule('karpus-mark-overdue', '0 10 * * *',
      $$ SELECT public.mark_overdue_payments(); $$);
    PERFORM cron.schedule('karpus-payment-reminders-daily', '0 13 * * *',
      $cmd$ SELECT net.http_post(
        url := 'https://TU_REF.supabase.co/functions/v1/payment-reminders',
        headers := '{"Content-Type":"application/json","Authorization":"Bearer TU_SERVICE_ROLE_KEY","apikey":"TU_SERVICE_ROLE_KEY"}'::jsonb,
        body := '{"action":"auto"}'::jsonb
      ); $cmd$);
    PERFORM cron.schedule('karpus-payment-cycle', '0 12 25 * *',
      $$ SELECT public.run_payment_cycle(); $$);
    PERFORM cron.schedule('annual-payment-generator', '0 3 1 1 *',
      $$ SELECT public.generate_annual_payments(EXTRACT(YEAR FROM CURRENT_DATE)::int); $$);
  END IF;
END $$;

