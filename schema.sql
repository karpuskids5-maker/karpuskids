CREATE OR REPLACE FUNCTION public.close_period(p_period_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_period record; v_student record;
  v_task_avg numeric; v_formal_avg numeric; v_final_score numeric; v_level text; v_count int := 0;
BEGIN
  SELECT * INTO v_period FROM public.periods WHERE id = p_period_id;
  IF NOT FOUND THEN RETURN jsonb_build_object('error', 'Periodo no encontrado'); END IF;
  IF v_period.status = 'closed' THEN RETURN jsonb_build_object('error', 'El periodo ya esta cerrado'); END IF;
  FOR v_student IN SELECT s.id, s.name, s.classroom_id, s.parent_id FROM public.students s
    WHERE (v_period.classroom_id IS NULL OR s.classroom_id = v_period.classroom_id) AND s.is_active = true
  LOOP
    SELECT avg(CASE WHEN grade_letter='A' THEN 4.0 WHEN grade_letter='B' THEN 3.0
      WHEN grade_letter='C' THEN 2.0 WHEN grade_letter='D' THEN 1.0 ELSE stars::numeric END) INTO v_task_avg
    FROM public.task_evidences te JOIN public.tasks t ON t.id = te.task_id
    WHERE te.student_id = v_student.id AND (t.period_id = p_period_id OR (t.period_id IS NULL AND t.created_at BETWEEN v_period.start_date AND v_period.end_date));
    SELECT avg(score) INTO v_formal_avg FROM public.grades WHERE student_id = v_student.id AND period_id = p_period_id;
    v_final_score := coalesce((coalesce(v_task_avg, 0) + coalesce(v_formal_avg, 0)) /
      case when v_task_avg is not null and v_formal_avg is not null then 2 else 1 end, 0);
    v_level := case when v_final_score >= 3.5 then 'Excelente' when v_final_score >= 2.5 then 'Bueno'
      when v_final_score >= 1.5 then 'En proceso' else 'Requiere apoyo' end;
    INSERT INTO public.report_cards (student_id, classroom_id, period_id, task_avg, formal_avg, final_score, level, generated_at)
    VALUES (v_student.id, v_student.classroom_id, p_period_id, v_task_avg, v_formal_avg, v_final_score, v_level, now())
    ON CONFLICT (student_id, period_id) DO UPDATE SET task_avg=excluded.task_avg, formal_avg=excluded.formal_avg,
      final_score=excluded.final_score, level=excluded.level, generated_at=now();
    INSERT INTO public.system_events (type, payload) VALUES ('report_card_generated', jsonb_build_object(
      'student_id',v_student.id,'student_name',v_student.name,'parent_id',v_student.parent_id,
      'period_name',v_period.name,'final_score',v_final_score,'level',v_level));
    v_count := v_count + 1;
  END LOOP;
  UPDATE public.periods SET status = 'closed', is_active = false WHERE id = p_period_id;
  RETURN jsonb_build_object('success', true, 'cards_generated', v_count);
END;
$$;
GRANT EXECUTE ON FUNCTION public.close_period(bigint) TO authenticated;

